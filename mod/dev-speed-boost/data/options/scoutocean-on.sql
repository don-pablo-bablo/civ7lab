-- Scouts cross oceans: On. Attaches modifiers from modifiers-gameeffects.xml
-- game-wide; it applies to every player's Scouts.
INSERT INTO GameModifiers (ModifierId) VALUES ('DSB_SCOUT_OCEAN_ON');

-- Exempt Scouts from the base game's ocean ban and embarkation types; see
-- SCOUT_OCEAN_EXEMPT in tools/build.py.
INSERT INTO Requirements (RequirementId, RequirementType, Inverse)
    VALUES ('DSB_REQ_NOT_SCOUT', 'REQUIREMENT_UNIT_TYPE_MATCHES', 1);
INSERT INTO RequirementArguments (RequirementId, Name, Value)
    VALUES ('DSB_REQ_NOT_SCOUT', 'UnitType', 'UNIT_SCOUT');
-- A modifier with no subject requirements gets a set of its own first.
INSERT INTO RequirementSets (RequirementSetId, RequirementSetType)
    SELECT 'DSB_REQSET_' || ModifierId, 'REQUIREMENTSET_TEST_ALL' FROM Modifiers
    WHERE ModifierId IN ('AGE_ANTIQUITY_MOD_OCEAN_TERRAIN_INVALID', 'AGE_ANTIQUITY_MOD_OCEAN_TERRAIN_INVALID_NOT_TEHINA', 'MOD_DEFAULT_CIV_RIVER_EMBARKATION', 'MOD_DEFAULT_CIV_RIVER_EMBARKATION_NOT_TEHINA', 'MOD_SAILING_EMBARKATION', 'MOD_SAILING_EMBARKATION_NOT_TEHINA', 'MOD_EXPLORATION_EMBARKATION') AND SubjectRequirementSetId IS NULL;
UPDATE Modifiers SET SubjectRequirementSetId = 'DSB_REQSET_' || ModifierId
    WHERE ModifierId IN ('AGE_ANTIQUITY_MOD_OCEAN_TERRAIN_INVALID', 'AGE_ANTIQUITY_MOD_OCEAN_TERRAIN_INVALID_NOT_TEHINA', 'MOD_DEFAULT_CIV_RIVER_EMBARKATION', 'MOD_DEFAULT_CIV_RIVER_EMBARKATION_NOT_TEHINA', 'MOD_SAILING_EMBARKATION', 'MOD_SAILING_EMBARKATION_NOT_TEHINA', 'MOD_EXPLORATION_EMBARKATION') AND SubjectRequirementSetId IS NULL;
INSERT INTO RequirementSetRequirements (RequirementSetId, RequirementId)
    SELECT SubjectRequirementSetId, 'DSB_REQ_NOT_SCOUT' FROM Modifiers
    WHERE ModifierId IN ('AGE_ANTIQUITY_MOD_OCEAN_TERRAIN_INVALID', 'AGE_ANTIQUITY_MOD_OCEAN_TERRAIN_INVALID_NOT_TEHINA', 'MOD_DEFAULT_CIV_RIVER_EMBARKATION', 'MOD_DEFAULT_CIV_RIVER_EMBARKATION_NOT_TEHINA', 'MOD_SAILING_EMBARKATION', 'MOD_SAILING_EMBARKATION_NOT_TEHINA', 'MOD_EXPLORATION_EMBARKATION');
